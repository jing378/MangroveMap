{{--
    Light / dark theme. Include as early as possible in <head>, before any stylesheet, so the
    theme is applied before the first paint (no flash of the light theme).

    The theme is <html data-theme="light|dark">. It follows the OS setting until the user picks one
    with a [data-theme-toggle] button (see partials.theme-toggle); the choice is kept in localStorage.

    Page colors come from partials.theme-palette, generated by scripts/theme/build-dark-theme.mjs.
    Below are only the styles that script cannot produce (third-party UI, form controls).
--}}
<script>
    (function () {
        var KEY = 'mangrovemap-theme';
        var root = document.documentElement;
        var media = window.matchMedia ? window.matchMedia('(prefers-color-scheme: dark)') : null;

        function stored() {
            try {
                var value = localStorage.getItem(KEY);
                return value === 'dark' || value === 'light' ? value : null;
            } catch (e) {
                return null;
            }
        }

        // Chart.js draws on a canvas, so CSS cannot reach it: set its default text/grid colors and
        // redraw open charts. Charts that hardcode colors can pass functions that read MangroveTheme.get().
        function styleCharts(theme) {
            var Chart = window.Chart;
            if (!Chart || !Chart.defaults) return;
            var dark = theme === 'dark';
            Chart.defaults.color = dark ? '#a3b9ab' : '#666';
            Chart.defaults.borderColor = dark ? 'rgba(255, 255, 255, 0.08)' : 'rgba(0, 0, 0, 0.1)';
            Object.values(Chart.instances || {}).forEach(function (chart) { chart.update('none'); });
        }

        function apply(theme) {
            root.setAttribute('data-theme', theme);
            styleCharts(theme);
            document.querySelectorAll('[data-theme-toggle]').forEach(function (button) {
                button.setAttribute('aria-pressed', theme === 'dark' ? 'true' : 'false');
            });
            document.dispatchEvent(new CustomEvent('themechange', { detail: { theme: theme } }));
        }

        function current() {
            return stored() || (media && media.matches ? 'dark' : 'light');
        }

        apply(current());

        window.MangroveTheme = {
            get: function () { return root.getAttribute('data-theme'); },
            set: function (theme) {
                try { localStorage.setItem(KEY, theme); } catch (e) {}
                apply(theme);
            },
            toggle: function () { this.set(this.get() === 'dark' ? 'light' : 'dark'); },
        };

        // Follow the OS while the user has not picked a theme.
        if (media && media.addEventListener) {
            media.addEventListener('change', function () { if (!stored()) apply(current()); });
        }
        // Keep other open tabs in sync.
        window.addEventListener('storage', function (e) { if (e.key === KEY) apply(current()); });

        document.addEventListener('click', function (e) {
            var button = e.target.closest && e.target.closest('[data-theme-toggle]');
            if (!button) return;
            e.preventDefault();
            window.MangroveTheme.toggle();
        });
        document.addEventListener('DOMContentLoaded', function () { apply(root.getAttribute('data-theme')); });
    })();
</script>

